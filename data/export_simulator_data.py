"""
Export the committed run output for the workspace simulator (app/simulator.html).
Reads data/output/*.parquet + evidence/* (produced by run_local_pipeline.py) and
writes app/sim_data.js. Nothing is invented: every number shown in the simulator
comes from these files.

Run:  python data/export_simulator_data.py
"""
from __future__ import annotations
import base64, json, sys
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "output"
EV = ROOT / "evidence"
sys.path.insert(0, str(ROOT / "data"))
import run_local_pipeline as pipe  # noqa: E402

tables = {
    "raw": ["subscribers", "contracts", "usage", "care_calls", "churn_labels"],
    "gold": ["subscriber_features", "save_list"],
}
files = {("raw", n): OUT / f"{n}.parquet" for n in tables["raw"]}
files[("gold", "subscriber_features")] = OUT / "gold_subscriber_features.parquet"
files[("gold", "save_list")] = OUT / "gold_save_list.parquet"
files[("silver", "care_calls_enriched")] = OUT / "call_enrichment.parquet"

catalog = []
for (schema, name), f in files.items():
    df = pd.read_parquet(f)
    catalog.append(dict(schema=schema, name=name, rows=int(len(df)),
                        columns=[[c, str(t)] for c, t in df.dtypes.items()],
                        sample=json.loads(df.head(8).astype(str).to_json(orient="values"))))

calls = pd.read_parquet(OUT / "care_calls.parquet")
enr, _ = pipe.enrich_calls(calls)
# one example per (intent, sentiment) pair, then fill to 14 rows, deterministic
picks = (enr.drop_duplicates(["intent", "sentiment", "transcript"])
            .groupby(["intent", "sentiment"]).head(2).head(14))
call_examples = picks[["call_id", "subscriber_id", "transcript", "sentiment", "intent", "switch_intent"]].to_dict("records")

usage = pd.read_parquet(OUT / "usage.parquet")
metrics = json.loads((EV / "model_metrics.json").read_text())
runlog = (EV / "model_run_output.txt").read_text()
meta = json.loads((OUT / "dataset_meta.json").read_text())

pipeline = dict(
    landing=meta["tables"],
    usage_months=int(usage.month.nunique()),
    sentiment_mix={k: int(v) for k, v in enr.sentiment.value_counts().items()},
    intent_mix={k: int(v) for k, v in enr.intent.value_counts().items()},
    switch_calls=int(enr.switch_intent.sum()),
)


def b64(p):
    return "data:image/png;base64," + base64.b64encode(Path(p).read_bytes()).decode()


logo_dir = ROOT / "app" / "assets"
sim = dict(catalog=catalog, calls=call_examples, metrics=metrics, pipeline=pipeline, runlog=runlog,
           logo_white=b64(logo_dir / "databricks_logo_white.png"), logo_mark=b64(logo_dir / "databricks_mark.png"))
(ROOT / "app" / "sim_data.js").write_text(
    "// generated by data/export_simulator_data.py from committed run output (synthetic data)\n"
    f"window.SIM = {json.dumps(sim)};\n")
print("wrote app/sim_data.js", {t["name"]: t["rows"] for t in catalog}, "calls:", len(call_examples))
